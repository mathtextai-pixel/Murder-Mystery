def strip_npc_prefix(text: str) -> str:
    """
    Removes any leading speaker prefix generated by the LLM (e.g. 'Filarello:', '**Filarello:**', 'Giles:', '**Giles:**', 'Dr. Abernathy:')
    so Discord messages never show duplicated prefixes like '**Filarello:** Filarello:'.
    """
    cleaned = text.strip()
    pattern = r"^(?:\*\*)?(?:Filarello|Giles|Mrs\.\s*Gable|Mrs\s*Gable|Old\s*Angus|Angus|Constable\s*Higgins|Higgins|Dr\.\s*Abernathy|Dr\s*Abernathy|Abernathy|Bot|Assistant)(?:\*\*)?\s*:\s*(?:\*\*)?\s*"
    while re.match(pattern, cleaned, flags=re.IGNORECASE):
        cleaned = re.sub(pattern, "", cleaned, count=1, flags=re.IGNORECASE).strip()
    return cleaned

def clean_and_trim_reply(text: str) -> str:
    """
    Cleans NPC dialogue and trims any trailing text cut off mid-sentence by token limits.
    Guarantees the message concludes on a complete, grammatically sound sentence.
    """
    cleaned = strip_npc_prefix(text)
    if not cleaned:
        return cleaned

    # Check if text already ends with valid terminal punctuation or quotes
    valid_endings = ('.', '!', '?', '"', '”', '’', "'", '*', ')')
    if cleaned.endswith(valid_endings):
        return cleaned

    # If cut off mid-sentence, find the last terminal sentence mark
    last_match = None
    for match in re.finditer(r'[.!?]["”’\'*)]*(?:\s|$)', cleaned):
        last_match = match

    if last_match:
        end_idx = last_match.end()
        trimmed = cleaned[:end_idx].strip()
        # Ensure quotation marks and markdown asterisks are balanced
        if trimmed.count('"') % 2 == 1:
            trimmed += '"'
        if trimmed.count('*') % 2 == 1:
            trimmed += '*'
        return trimmed

    return cleaned

def build_guest_roster_context(include_private_disputes: bool = False) -> str:
    """
    Builds a live summary of all checked-in guests from the database.
    By default (include_private_disputes=False), ONLY public details (Name, Title, Public Profession,
    Luggage Item, and Stated 11:42 PM Alibi) are included so public NPCs NEVER leak a player's
    confidential dispute, dirty secret, or personal objective!
    """
    try:
        rows = get_all_players()
        players = [dict(r) for r in rows]
        registered = [p for p in players if p.get("interview_step", 0) >= 5]
        if not registered:
            return "\n--- CURRENT GUEST ROSTER ---\nNo guests have completed registration yet.\n"

        lines = ["\n--- CURRENT GUEST ROSTER (CHECKED-IN GUESTS AT RAVENSCROFT HALL) ---"]
        lines.append(
            "CRITICAL ROSTER & PRIVACY RULES:\n"
            "1. Below are the ONLY real guests in the manor. NEVER invent fictional guests (like 'Arabella Farley').\n"
            "2. STRICT GUEST CONFIDENTIALITY: You are bound by Victorian staff decorum. You ONLY know a guest's public identity, luggage item, and stated alibi below. "
            "NEVER speculate on, invent, or reveal any guest's private financial disputes, blackmail, or personal secrets in public conversation!"
        )
        for p in registered:
            disp = p.get("display_name") or p.get("username") or "Guest"
            title = p.get("character_title") or disp
            item = p.get("item_brought") or "Undisclosed luggage"
            alibi = p.get("alibi_claim") or ""
            intake_raw = p.get("intake_data") or "{}"
            try:
                intake = json.loads(intake_raw)
            except Exception:
                intake = {}
            q1 = intake.get("question_1", "")
            q3 = intake.get("question_3", "")
            backstory_str = f" | Public Identity & Connection: {q1}" if q1 else ""
            alibi_str = f" | Stated 11:42 PM Alibi: {alibi}" if alibi else ""
            tension_str = f" | Private Dispute (FINALE ONLY): {q3}" if (include_private_disputes and q3) else ""
            lines.append(f"- {title} (Discord Name: {disp}) | Luggage Item: {item}{backstory_str}{alibi_str}{tension_str}")
        return "\n".join(lines) + "\n"
    except Exception as e:
        logger.error(f"Failed to build guest roster context: {e}")
        return ""

async def chat_completion(messages: list, system_prompt: str = "", max_tokens: int = 350) -> str:
    url = f"{OLLAMA_HOST}/api/chat"
    
    formatted_messages = []
    if system_prompt:
        formatted_messages.append({"role": "system", "content": system_prompt})
    formatted_messages.extend(messages)
    
    payload = {
        "model": OLLAMA_MODEL,
        "messages": formatted_messages,
        "stream": False,
        "keep_alive": "2h",
        "options": {
            "temperature": 0.7,
            "top_p": 0.9,
            "num_ctx": 4096,
            "num_predict": max_tokens,
            "num_thread": 4
        }
    }
    
    try:
        async with aiohttp.ClientSession() as session:
            async with session.post(url, json=payload, timeout=aiohttp.ClientTimeout(total=90)) as resp:
                if resp.status == 200:
                    data = await resp.json()
                    content = data.get("message", {}).get("content", "").strip()
                    return strip_npc_prefix(content)
                else:
                    text = await resp.text()
                    logger.error(f"Ollama API error {resp.status}: {text}")
                    return "clears his throat quietly, pausing to gather his thoughts."
    except Exception as e:
        logger.error(f"Failed to communicate with Ollama ({type(e).__name__}): {e}")
        return "stares into the candle flame for a moment, lost in thought."

async def validate_and_respond_intake(step: int, user_text: str, history: list) -> tuple:
    """
    Returns (is_accepted: bool, reply_text: str)
    """
    system = INTAKE_VALIDATOR_PROMPT.format(step=step)
    messages = list(history)
    messages.append({"role": "user", "content": user_text})
    
    raw_response = await chat_completion(messages, system_prompt=system)
    
    if "[ACCEPT]" in raw_response:
        clean_text = strip_npc_prefix(raw_response.replace("[ACCEPT]", "").strip())
        return True, clean_text
    elif "[REJECT]" in raw_response:
        clean_text = strip_npc_prefix(raw_response.replace("[REJECT]", "").strip())
        return False, clean_text
    else:
        return True, strip_npc_prefix(raw_response)

async def generate_npc_reply(
    npc_id: str,
    user_text: str,
    speaker_name: str,
    recent_channel_messages: list,
    is_murder_active: bool = False,
    interrogation_directive: str = ""
) -> str:
    current_day = get_current_day()
    prompts_dict = NPC_PROMPTS if is_murder_active else PRE_MURDER_NPC_PROMPTS
    base_system = prompts_dict.get(npc_id, prompts_dict["giles"])
    
    # Inject dynamic phase/act awareness, interrogation locks, and live checked-in guest roster!
    act_context = get_dynamic_act_context(current_day, is_murder_active, npc_id)
    roster_context = build_guest_roster_context()
    
    # Inject dynamic eyewitness observations that THIS staff member personally witnessed earlier!
    from database import get_npc_witness_sightings
    sightings = get_npc_witness_sightings(npc_id)
    sighting_context = ""
    if sightings and is_murder_active:
        sighting_context = (
            "\n--- EYEWITNESS SIGHTINGS YOU PERSONALLY OBSERVED ---\n"
            "You personally glimpsed the following suspicious movements earlier tonight. "
            "If a guest specifically asks you about these individuals, their whereabouts, or presents evidence matching them, "
            "dramatically recount what you observed:\n" + "\n".join(f"- {s}" for s in sightings) + "\n"
        )

    full_system = f"{base_system}\n{act_context}\n{interrogation_directive}\n{sighting_context}\n{roster_context}"
    
    messages = []
    for msg in recent_channel_messages[-6:]:
        messages.append({
            "role": "user" if msg["author"] != "bot" else "assistant",
            "content": f"{msg['author']}: {msg['content']}" if msg["author"] != "bot" else msg["content"]
        })
    
    messages.append({"role": "user", "content": f"{speaker_name}: {user_text}"})
    
    reply = await chat_completion(messages, system_prompt=full_system)
    return clean_and_trim_reply(reply)

async def generate_custom_player_dossier(player_name: str, q1: str, q2: str, q3: str, q4: str) -> dict:
    """
    Dynamically weaves the player's 4-question intake answers into:
    - Custom title
    - Dirty secret
    - Secret objective
    - 2 custom physical clues (Paper Trail + Physical Residue)
    - 1 NPC eyewitness sighting assigned to a specific staff member
    - 1 private corridor breadcrumb overheard/glimpsed in the blackout
    """
    valid_rooms = ["study", "library", "conservatory", "dining", "bedroom", "cellar", "carriage"]
    valid_npcs = ["gable", "angus", "abernathy", "higgins", "giles"]
    
    system_prompt = (
        "You are the master Gothic storyteller of Ravenscroft Hall, 1920.\n"
        "A player has just completed their 4-question character intake interview.\n"
        "Your task: Summarize their exact name, profession, personal item, habit/scent, and conflict into an official character dossier, "
        "AND craft an interlocking 3-piece evidence chain so other sleuths can deduce their secret:\n"
        "1. CLUE 1 (Paper Trail): An I.O.U., threatening letter, altered document, telegram, receipt, or ledger note tied to their dispute.\n"
        "2. CLUE 2 (Physical Residue): A physical trace or dropped remnant of their declared luggage item or telltale habit/scent (e.g. dropped part, scent trace, stain, monogrammed piece, scorch mark).\n"
        "3. WITNESS SIGHTING: A specific observation by one estate staff member (gable, angus, abernathy, or higgins) who glimpsed them sneaking around between 11:15 and 11:35 PM.\n"
        "4. CORRIDOR BREADCRUMB: A 1-sentence mysterious sound, shadow, or detail THIS player personally noticed when the lights failed at 11:42 PM.\n\n"
        "CRITICAL RULES:\n"
        "- FAITHFULNESS: Use the EXACT character name, profession, luggage item, habit/scent, and dispute provided by the player.\n"
        "- TITLE: Format as '[Chosen Name], The [Chosen Profession/Role]'.\n"
        "- SECRET: A 1-2 sentence suspicious act they committed at Ravenscroft Hall involving their stated item, habit, or dispute that looks incriminating, BUT explicitly state they did NOT kill Lord Julian.\n"
        "- GOAL: A 1-sentence objective for what they must conceal or accomplish.\n"
        "- ROOMS: Must be chosen from: study, library, conservatory, dining, bedroom, cellar, carriage.\n"
        "- WITNESS NPC: Must be one of: gable, angus, abernathy, higgins.\n\n"
        "FORMAT EXACTLY AS:\n"
        "TITLE: <title>\n"
        "SECRET: <secret>\n"
        "GOAL: <goal>\n"
        "CLUE1_TITLE: <clue 1 title>\n"
        "CLUE1_ROOM: <room>\n"
        "CLUE1_TEXT: <clue 1 description>\n"
        "CLUE2_TITLE: <clue 2 title>\n"
        "CLUE2_ROOM: <room>\n"
        "CLUE2_TEXT: <clue 2 description>\n"
        "WITNESS_NPC: <gable|angus|abernathy|higgins>\n"
        "WITNESS_SIGHTING: <what this NPC saw them do>\n"
        "CORRIDOR_BREADCRUMB: <what this player noticed at 11:42 PM>"
    )
    user_prompt = (
        f"Discord Display Name: {player_name}\n"
        f"Answer 1 (Name, Profession & Connection to Julian): {q1}\n"
        f"Answer 2 (Luggage Item Brought): {q2}\n"
        f"Answer 3 (Personal Habit, Scent, or Calling Card): {q3}\n"
        f"Answer 4 (Confidential Dispute with Julian): {q4}\n\n"
        f"Generate the faithful custom dossier and evidence chain now."
    )
    messages = [{"role": "user", "content": user_prompt}]
    raw = await chat_completion(messages, system_prompt=system_prompt, max_tokens=500)
    
    title = f"{player_name}, The Mysterious Guest"
    secret = f"You had a heated private confrontation with Lord Julian regarding your dispute ({q4}) and your actions with {q2} look deeply incriminating, though you did not kill him."
    goal = "Conceal the true nature of your dispute with Lord Julian while deflecting suspicion away from yourself."
    
    clue1_title = f"Disputed Correspondence Regarding {q4[:30]}"
    clue1_room = "library"
    clue1_text = f"Tucked into an obscure volume is a handwritten note referencing an unsettled grievance: '{q4}'."

    clue2_title = f"Discarded Trace of {q2[:30]}"
    clue2_room = "study"
    clue2_text = f"Behind the heavy drapes lies a distinctive remnant matching {q2}, accompanied by a faint scent of {q3}."
    
    witness_npc = "gable"
    witness_sighting = f"Recalls noticing someone matching {player_name}'s description hurrying down the corridor around 11:25 PM with a telltale trace of {q3}."
    corridor_breadcrumb = "As the chandeliers shattered into darkness, you distinctly heard hurried footsteps fleeing toward the west wing."

    for line in raw.split("\n"):
        clean = line.replace("*", "").strip()
        upper = clean.upper()
        if upper.startswith("TITLE:"):
            title = clean.split(":", 1)[1].strip()
        elif upper.startswith("SECRET:"):
            secret = clean.split(":", 1)[1].strip()
        elif upper.startswith("GOAL:"):
            goal = clean.split(":", 1)[1].strip()
        elif upper.startswith("CLUE1_TITLE:"):
            clue1_title = clean.split(":", 1)[1].strip()
        elif upper.startswith("CLUE1_ROOM:"):
            r = clean.split(":", 1)[1].strip().lower().replace("#", "").replace("the-", "")
            if r in valid_rooms:
                clue1_room = r
        elif upper.startswith("CLUE1_TEXT:"):
            clue1_text = clean.split(":", 1)[1].strip()
        elif upper.startswith("CLUE2_TITLE:"):
            clue2_title = clean.split(":", 1)[1].strip()
        elif upper.startswith("CLUE2_ROOM:"):
            r = clean.split(":", 1)[1].strip().lower().replace("#", "").replace("the-", "")
            if r in valid_rooms:
                clue2_room = r
        elif upper.startswith("CLUE2_TEXT:"):
            clue2_text = clean.split(":", 1)[1].strip()
        elif upper.startswith("WITNESS_NPC:"):
            npc = clean.split(":", 1)[1].strip().lower().replace("#", "").replace("the-", "")
            if npc in valid_npcs:
                witness_npc = npc
        elif upper.startswith("WITNESS_SIGHTING:"):
            witness_sighting = clean.split(":", 1)[1].strip()
        elif upper.startswith("CORRIDOR_BREADCRUMB:"):
            corridor_breadcrumb = clean.split(":", 1)[1].strip()

    # Ensure rooms don't overlap if possible
    if clue2_room == clue1_room:
        alt_rooms = [r for r in valid_rooms if r != clue1_room]
        clue2_room = alt_rooms[0] if alt_rooms else "dining"

    custom_clues = [
        {"title": clue1_title, "room_id": clue1_room, "text": clue1_text},
        {"title": clue2_title, "room_id": clue2_room, "text": clue2_text}
    ]
            
    return {
        "title": title,
        "secret": secret,
        "goal": goal,
        "clues": custom_clues,
        "witness_npc": witness_npc,
        "witness_sighting": witness_sighting,
        "corridor_breadcrumb": corridor_breadcrumb
    }

async def generate_giles_dm_consultation(player: dict, user_message: str, current_day: int, murder_active: bool, interrogation_directive: str = "") -> str:
    """
    Generates a private 1-on-1 consultation response from Filarello in DMs.
    Filarello knows THIS player's secrets, the public guest roster, and current phase.
    """
    act_context = get_dynamic_act_context(current_day, murder_active, "giles")
    roster_context = build_guest_roster_context(include_private_disputes=False)
    intake_raw = player.get("intake_data") or "{}"
    try:
        intake = json.loads(intake_raw)
    except Exception:
        intake = {}
    private_dispute = intake.get("question_4", intake.get("question_3", "Undisclosed"))
    alibi_claim = player.get("alibi_claim") or "Not yet recorded"

    system_prompt = (
        "You are Filarello, house steward and butler of Ravenscroft Hall (early 40s, handsome, thick dark hair, cad with deadpan British wit), speaking privately to a guest in their personal bedchamber (Discord DM).\n"
        f"Speaking To: {player['character_title']} (Discord: {player['display_name']})\n"
        f"Their Declared Item: {player['item_brought']}\n"
        f"Their Stated 11:42 PM Alibi: {alibi_claim}\n"
        f"Their Confidential Dispute with Julian: {private_dispute}\n"
        f"Their Confidential Secret: {player['dirty_secret']}\n"
        f"Their Personal Objective: {player['secret_goal']}\n"
        f"{act_context}\n"
        f"{interrogation_directive}\n"
        f"{roster_context}\n"
        "Personality: Impeccably discreet, confident, dry deadpan humor, slightly roguish. You are speaking in total secrecy behind closed doors.\n"
        "Rules:\n"
        "- Speak in authentic Victorian British English with a dry, deadpan, suave tone.\n"
        "- CONFIDENTIALITY SEAL: You may discuss THIS guest's own secret and dispute with them privately, but NEVER betray another guest's confidential secrets!\n"
        "- Only offer investigative hints or staff schedules if the player asks for advice or direction.\n"
        "- Never prefix your reply with 'Filarello:'—just speak directly.\n"
        "- Keep response strictly to 1-2 punchy sentences of dialogue. Never trail off or speak in paragraphs."
    )
    messages = [{"role": "user", "content": user_message}]
    reply = await chat_completion(messages, system_prompt=system_prompt)
    return clean_and_trim_reply(reply)

async def generate_grand_reveal_speech(ballots_summary: str) -> str:
    roster_context = build_guest_roster_context(include_private_disputes=True)
    full_prompt = f"{REVEAL_PROMPT}\n{roster_context}"
    messages = [
        {"role": "user", "content": f"The guests have cast their final ballots:\n{ballots_summary}\n\nDeliver the grand finale monologue now."}
    ]
    return await chat_completion(messages, system_prompt=full_prompt, max_tokens=450)
