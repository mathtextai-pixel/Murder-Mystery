def strip_npc_prefix(text: str) -> str:
    """
    Removes any leading speaker prefix generated by the LLM (e.g. 'Giles:', '**Giles:**', 'Dr. Abernathy:')
    so Discord messages never show duplicated prefixes like '**Giles:** Giles:'.
    """
    cleaned = text.strip()
    pattern = r"^(?:\*\*)?(?:Giles|Mrs\.\s*Gable|Mrs\s*Gable|Old\s*Angus|Angus|Constable\s*Higgins|Higgins|Dr\.\s*Abernathy|Dr\s*Abernathy|Abernathy|Bot|Assistant)(?:\*\*)?\s*:\s*(?:\*\*)?\s*"
    while re.match(pattern, cleaned, flags=re.IGNORECASE):
        cleaned = re.sub(pattern, "", cleaned, count=1, flags=re.IGNORECASE).strip()
    return cleaned

def build_guest_roster_context() -> str:
    """
    Builds a live summary of all checked-in guests from the database, including their
    Discord name, character title, declared luggage item, and interview backstory.
    """
    try:
        rows = get_all_players()
        players = [dict(r) for r in rows]
        registered = [p for p in players if p.get("interview_step", 0) >= 4]
        if not registered:
            return "\n--- CURRENT GUEST ROSTER ---\nNo guests have completed registration yet.\n"

        lines = ["\n--- CURRENT GUEST ROSTER (CHECKED-IN GUESTS AT RAVENSCROFT HALL) ---"]
        lines.append("CRITICAL RULE: Below are the ONLY real guests in the manor. NEVER invent fictional guests (like 'Arabella Farley'). When asked about a guest, refer to their real details below:")
        for p in registered:
            disp = p.get("display_name") or p.get("username") or "Guest"
            title = p.get("character_title") or disp
            item = p.get("item_brought") or "Undisclosed luggage"
            intake_raw = p.get("intake_data") or "{}"
            try:
                intake = json.loads(intake_raw)
            except Exception:
                intake = {}
            q1 = intake.get("question_1", "")
            q3 = intake.get("question_3", "")
            backstory_str = f" | Interview Background: {q1}" if q1 else ""
            tension_str = f" | Known Dispute with Julian: {q3}" if q3 else ""
            lines.append(f"- {title} (Discord Name: {disp}) | Luggage Item: {item}{backstory_str}{tension_str}")
        return "\n".join(lines) + "\n"
    except Exception as e:
        logger.error(f"Failed to build guest roster context: {e}")
        return ""

async def chat_completion(messages: list, system_prompt: str = "", max_tokens: int = 250) -> str:
    url = f"{OLLAMA_HOST}/api/chat"
    
    formatted_messages = []
    if system_prompt:
        formatted_messages.append({"role": "system", "content": system_prompt})
    formatted_messages.extend(messages)
    
    payload = {
        "model": OLLAMA_MODEL,
        "messages": formatted_messages,
        "stream": False,
        "keep_alive": "2h",
        "options": {
            "temperature": 0.7,
            "top_p": 0.9,
            "num_ctx": 4096,
            "num_predict": max_tokens,
            "num_thread": 6
        }
    }
    
    try:
        async with aiohttp.ClientSession() as session:
            async with session.post(url, json=payload, timeout=aiohttp.ClientTimeout(total=90)) as resp:
                if resp.status == 200:
                    data = await resp.json()
                    content = data.get("message", {}).get("content", "").strip()
                    return strip_npc_prefix(content)
                else:
                    text = await resp.text()
                    logger.error(f"Ollama API error {resp.status}: {text}")
                    return "clears his throat quietly, pausing to gather his thoughts."
    except Exception as e:
        logger.error(f"Failed to communicate with Ollama ({type(e).__name__}): {e}")
        return "stares into the candle flame for a moment, lost in thought."

async def validate_and_respond_intake(step: int, user_text: str, history: list) -> tuple:
    """
    Returns (is_accepted: bool, reply_text: str)
    """
    system = INTAKE_VALIDATOR_PROMPT.format(step=step)
    messages = list(history)
    messages.append({"role": "user", "content": user_text})
    
    raw_response = await chat_completion(messages, system_prompt=system)
    
    if "[ACCEPT]" in raw_response:
        clean_text = strip_npc_prefix(raw_response.replace("[ACCEPT]", "").strip())
        return True, clean_text
    elif "[REJECT]" in raw_response:
        clean_text = strip_npc_prefix(raw_response.replace("[REJECT]", "").strip())
        return False, clean_text
    else:
        return True, strip_npc_prefix(raw_response)

async def generate_npc_reply(
    npc_id: str,
    user_text: str,
    speaker_name: str,
    recent_channel_messages: list,
    is_murder_active: bool = False,
    interrogation_directive: str = ""
) -> str:
    current_day = get_current_day()
    prompts_dict = NPC_PROMPTS if is_murder_active else PRE_MURDER_NPC_PROMPTS
    base_system = prompts_dict.get(npc_id, prompts_dict["giles"])
    
    # Inject dynamic phase/act awareness, interrogation locks, and live checked-in guest roster!
    act_context = get_dynamic_act_context(current_day, is_murder_active, npc_id)
    roster_context = build_guest_roster_context()
    full_system = f"{base_system}\n{act_context}\n{interrogation_directive}\n{roster_context}"
    
    messages = []
    for msg in recent_channel_messages[-6:]:
        messages.append({
            "role": "user" if msg["author"] != "bot" else "assistant",
            "content": f"{msg['author']}: {msg['content']}" if msg["author"] != "bot" else msg["content"]
        })
    
    messages.append({"role": "user", "content": f"{speaker_name}: {user_text}"})
    
    reply = await chat_completion(messages, system_prompt=full_system)
    return strip_npc_prefix(reply)

async def generate_custom_player_dossier(player_name: str, q1: str, q2: str, q3: str) -> dict:
    """
    Dynamically weaves the player's freely chosen profession, item, and dispute into
    a custom title, dirty secret, and secret objective.
    """
    system_prompt = (
        "You are the master Gothic storyteller of Ravenscroft Hall.\n"
        "A player has just completed their 3-question registration interview.\n"
        "Your task: Summarize their exact stated name, profession, personal item, and conflict into an official character dossier.\n"
        "CRITICAL ACCURACY RULES:\n"
        "- FAITHFULNESS: Use the EXACT character name, profession, relation, item, and dispute the player provided in their answers! Do NOT change their name, gender, or trade.\n"
        "- TITLE: Format as '[Their Chosen Name], The [Their Chosen Profession/Role]' (e.g., 'Penelope Vance, The Antiquarian').\n"
        "- SECRET: A 1-2 sentence suspicious act they committed at Ravenscroft Hall involving their stated item or dispute that looks incriminating, BUT explicitly state they did NOT kill Lord Julian.\n"
        "- GOAL: A 1-sentence objective for what they must conceal or accomplish during the investigation.\n\n"
        "FORMAT EXACTLY AS:\n"
        "TITLE: <title>\n"
        "SECRET: <secret>\n"
        "GOAL: <goal>"
    )
    user_prompt = (
        f"Discord Display Name: {player_name}\n"
        f"Answer 1 (Name, Profession & Relation to Julian): {q1}\n"
        f"Answer 2 (Personal Item Brought): {q2}\n"
        f"Answer 3 (Dispute/Tension with Julian): {q3}\n\n"
        f"Generate the faithful custom dossier now."
    )
    messages = [{"role": "user", "content": user_prompt}]
    raw = await chat_completion(messages, system_prompt=system_prompt)
    
    title = f"{player_name}, The Mysterious Guest"
    secret = f"You had a heated private confrontation with Lord Julian regarding your dispute ({q3}) and used your {q2} in a way that looks deeply suspicious, though you did not kill him."
    goal = "Conceal the true nature of your dispute with Lord Julian while uncovering the real murderer."
    
    for line in raw.split("\n"):
        clean_line = line.replace("*", "").strip()
        if clean_line.upper().startswith("TITLE:"):
            title = clean_line.split(":", 1)[1].strip()
        elif clean_line.upper().startswith("SECRET:"):
            secret = clean_line.split(":", 1)[1].strip()
        elif clean_line.upper().startswith("GOAL:"):
            goal = clean_line.split(":", 1)[1].strip()
            
    return {"title": title, "secret": secret, "goal": goal}

async def generate_giles_dm_consultation(player: dict, user_message: str, current_day: int, murder_active: bool, interrogation_directive: str = "") -> str:
    """
    Generates a private 1-on-1 consultation response from Giles in DMs.
    Giles knows the player's secrets, the full guest roster, and current phase.
    """
    act_context = get_dynamic_act_context(current_day, murder_active, "giles")
    roster_context = build_guest_roster_context()
    system_prompt = (
        "You are Giles, senior house steward of Ravenscroft Hall, speaking privately to a guest in their personal bedchamber (Discord DM).\n"
        f"Speaking To: {player['character_title']} (Discord: {player['display_name']})\n"
        f"Their Declared Item: {player['item_brought']}\n"
        f"Their Confidential Secret: {player['dirty_secret']}\n"
        f"Their Personal Objective: {player['secret_goal']}\n"
        f"{act_context}\n"
        f"{interrogation_directive}\n"
        f"{roster_context}\n"
        "Personality: Impeccably discreet, formal, loyal to Ravenscroft hospitality. You are speaking in total secrecy behind closed doors.\n"
        "Rules:\n"
        "- Speak in authentic Victorian British English.\n"
        "- Only offer investigative hints or staff schedules if the player asks for advice or direction.\n"
        "- Never prefix your reply with 'Giles:'—just speak directly.\n"
        "- Keep response to 2-3 sentences."
    )
    messages = [{"role": "user", "content": user_message}]
    reply = await chat_completion(messages, system_prompt=system_prompt)
    return strip_npc_prefix(reply)

async def generate_grand_reveal_speech(ballots_summary: str) -> str:
    roster_context = build_guest_roster_context()
    full_prompt = f"{REVEAL_PROMPT}\n{roster_context}"
    messages = [
        {"role": "user", "content": f"The guests have cast their final ballots:\n{ballots_summary}\n\nDeliver the grand finale monologue now."}
    ]
    return await chat_completion(messages, system_prompt=full_prompt, max_tokens=450)
